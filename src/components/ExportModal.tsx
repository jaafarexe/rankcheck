import React, { useState } from 'react';
import { AuditReport } from '../types/seo';
import { X, Copy, Check, Download, Printer, FileText } from 'lucide-react';

interface ExportModalProps {
  report: AuditReport;
  isOpen: boolean;
  onClose: () => void;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  report,
  isOpen,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = () => {
    return `# SEO Audit Report - RankCheck
**Target URL:** ${report.url}  
**Audit Date:** ${report.auditedAt}  
**Overall Health Score:** ${report.overallScore}/100 (Grade ${report.grade})  
**Status:** ${report.statusLabel}  

## Category Performance
- **On-Page SEO:** ${report.categories['on-page'].score}/100 (${report.categories['on-page'].passedCount} Pass, ${report.categories['on-page'].warningCount} Warn, ${report.categories['on-page'].failCount} Fail)
- **Technical SEO:** ${report.categories['technical'].score}/100 (${report.categories['technical'].passedCount} Pass, ${report.categories['technical'].warningCount} Warn, ${report.categories['technical'].failCount} Fail)
- **Content:** ${report.categories['content'].score}/100 (${report.categories['content'].passedCount} Pass, ${report.categories['content'].warningCount} Warn, ${report.categories['content'].failCount} Fail)
- **Mobile:** ${report.categories['mobile'].score}/100 (${report.categories['mobile'].passedCount} Pass, ${report.categories['mobile'].warningCount} Warn, ${report.categories['mobile'].failCount} Fail)
- **Performance:** ${report.categories['performance'].score}/100 (${report.categories['performance'].passedCount} Pass, ${report.categories['performance'].warningCount} Warn, ${report.categories['performance'].failCount} Fail)

## Priority Fixes & Recommendations
${report.items
  .filter((it) => it.status !== 'pass')
  .map(
    (it) => `### [${it.status.toUpperCase()}] ${it.title} (${it.category.toUpperCase()} - ${it.impact.toUpperCase()} IMPACT)
- **Finding:** ${it.detected}
- **Recommendation:** ${it.recommendation}
${it.fixCodeSnippet ? `\`\`\`html\n${it.fixCodeSnippet}\n\`\`\`` : ''}
`
  )
  .join('\n')}

---
*Report generated by RankCheck - SEO Audit*
`;
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdown());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadMarkdown = () => {
    const text = generateMarkdown();
    const blob = new Blob([text], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `rankcheck-audit-${report.pageStats.hostname}.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
      <div className="bg-white rounded-2xl max-w-lg w-full p-6 shadow-xl border border-slate-200">
        <div className="flex items-center justify-between pb-4 border-b border-slate-100">
          <div className="flex items-center gap-2">
            <div className="p-1.5 rounded-md bg-slate-100 text-slate-800">
              <FileText className="w-4 h-4" />
            </div>
            <h3 className="text-base font-bold text-slate-900">
              Export SEO Audit Report
            </h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="p-1 text-slate-400 hover:text-slate-600 rounded-md transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="py-4 space-y-3">
          <p className="text-xs text-slate-600">
            Share this audit with team members, clients, or engineers. Download the structured Markdown report, copy to clipboard, or print a formatted PDF summary.
          </p>

          <div className="p-3 bg-slate-50 rounded-lg border border-slate-200 text-xs space-y-1 font-mono">
            <div className="flex justify-between">
              <span className="text-slate-500">Website:</span>
              <span className="font-semibold text-slate-800">{report.pageStats.hostname}</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-500">Overall Score:</span>
              <span className="font-bold text-emerald-700">{report.overallScore}/100 ({report.grade})</span>
            </div>
            <div className="flex justify-between">
              <span className="text-slate-500">Total Issues:</span>
              <span className="text-slate-800">
                {report.items.filter((i) => i.status === 'fail').length} Fails,{' '}
                {report.items.filter((i) => i.status === 'warning').length} Warnings
              </span>
            </div>
          </div>

          <div className="grid grid-cols-1 gap-2 pt-2">
            <button
              type="button"
              onClick={handleDownloadMarkdown}
              className="flex items-center justify-center gap-2 w-full py-2.5 px-4 bg-slate-900 hover:bg-slate-800 text-white font-semibold text-xs rounded-lg transition-colors cursor-pointer shadow-xs"
            >
              <Download className="w-4 h-4" />
              <span>Download Markdown Report (.md)</span>
            </button>

            <button
              type="button"
              onClick={handleCopyMarkdown}
              className="flex items-center justify-center gap-2 w-full py-2.5 px-4 bg-white hover:bg-slate-50 text-slate-700 font-semibold text-xs rounded-lg border border-slate-200 transition-colors cursor-pointer"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-emerald-600" />
                  <span className="text-emerald-700">Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-slate-500" />
                  <span>Copy Report Summary to Clipboard</span>
                </>
              )}
            </button>

            <button
              type="button"
              onClick={handlePrint}
              className="flex items-center justify-center gap-2 w-full py-2.5 px-4 bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold text-xs rounded-lg transition-colors cursor-pointer"
            >
              <Printer className="w-4 h-4 text-slate-500" />
              <span>Print / Save as PDF</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
